class SetEx {
    public static void main(String[] args) {
        java.util.Set<String> set = new java.util.HashSet<>();
        set.add("Hello");
        set.add("World");
        set.add("Hello"); // 중복된 요소는 추가되지 않음

        System.out.println(set); // 출력: [Hello, World]
    }
}

